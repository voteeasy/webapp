package de.voteeasy.selfservice;

import jakarta.servlet.http.HttpServletRequest;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import uk.org.okapibarcode.backend.HumanReadableLocation;
import uk.org.okapibarcode.backend.OkapiInputException;
import uk.org.okapibarcode.backend.QrCode;
import uk.org.okapibarcode.graphics.Color;
import uk.org.okapibarcode.output.Java2DRenderer;

import javax.imageio.ImageIO;
import java.awt.*;
import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.Optional;

@Service
@Slf4j
public class QrCodeService {

    /**
     * Creates a {@link QrCode} with a link generated by {@link #generateLink(HttpServletRequest, QrCodeParameter)}.
     *
     * @param request         request to verify if the app runs locally or is deployed somewhere.
     * @param qrCodeParameter QR-code input parameters that are added to the underlying URL.
     * @return QR code. If the content cannot be set as expected an empty URL is returned.
     */
    QrCode createQrCode(HttpServletRequest request, QrCodeParameter qrCodeParameter) {
        QrCode barcode = new QrCode();
        try {
            barcode.setFontName("Monospaced");
            barcode.setFontSize(16);
            barcode.setModuleWidth(2);
            barcode.setBarHeight(50);
            barcode.setHumanReadableLocation(HumanReadableLocation.BOTTOM);
            barcode.setContent(generateLink(request, qrCodeParameter));
        } catch (OkapiInputException e) {
            log.error("Will return empty QR code due to: {}", e.getMessage());
            barcode.setContent("Something went wrong");
        }
        return barcode;
    }

    /**
     * Performs the rendering of a barcode as an image.
     *
     * @param httpServletRequest request to verify if the app runs locally or is deployed somewhere.
     * @param qrCodeParameter    QR-code input parameters that are added to the underlying URL.
     * @return a completely rendered QR code as {@code PNG} image. In case of IO errors an empty byte array will be returned that does not work as a QR code.
     */
    public byte[] renderQrCode(HttpServletRequest httpServletRequest, QrCodeParameter qrCodeParameter) {
        QrCode barcode = createQrCode(httpServletRequest, qrCodeParameter);

        // was TYPE_BYTE_GRAY
        BufferedImage image = new BufferedImage(barcode.getWidth(), barcode.getHeight(), BufferedImage.TYPE_INT_RGB);
        Graphics2D g2d = image.createGraphics();
        Java2DRenderer renderer = new Java2DRenderer(g2d, 1, qrCodeParameter.getInkColor(), qrCodeParameter.getPaperColor());
        renderer.render(barcode);

        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            ImageIO.write(image, "png", out);
            return out.toByteArray();
        } catch (IOException e) {
            log.error("Will return empty QR code image due to: {}", e.getMessage());
            return new byte[]{};
        }
    }

    /**
     * Generates a complete URL with all parameters extracted from the given parameters.
     *
     * @param request         request used to determine if running locally. If the request's URL contains {@code localhost} the generated URL contains the local address and port instead of the live URL.
     * @param qrCodeParameter QR-code input parameters that are added to the underlying URL.
     * @return a completely rendered link with parameters.
     */
    String generateLink(HttpServletRequest request, QrCodeParameter qrCodeParameter) {
        String host = request.getLocalName();
        StringBuilder url = new StringBuilder();

        if (host != null && host.contains("localhost")) {
            //noinspection HttpUrlsUsage
            url.append("http://").append(host).append(":").append(request.getLocalPort());
        } else {
            // example: https://login.yourvoteeasy.de
            url.append("http://localhost:8080");
        }

        url.append("/login?tt=").append(qrCodeParameter.tenant()) //
                .append("&uu=").append(qrCodeParameter.user()) //
                .append("&pp=").append(qrCodeParameter.password());

        return url.toString();
    }

    /**
     * Simple DTO for QR code generation.
     *
     * @param tenant   tenant/organisation name to use.
     * @param user     username.
     * @param password password.
     * @param ink      foreground color of the QR code.
     * @param paper    background color of the QR code.
     */
    public record QrCodeParameter(String tenant, String user, String password, Optional<String> ink,
                                  Optional<String> paper) {

        /**
         * @return ink color, fallback default is {@code WHITE}.
         */
        Color getInkColor() {
            return ColorMapper.getColor(ink, Color.WHITE);
        }

        /**
         * @return paper color, fallback default is {@code BLACK}.
         */
        Color getPaperColor() {
            return ColorMapper.getColor(ink, Color.BLACK);
        }

    }

    /**
     * Helper class to map and use predefined and other RGB colors in QR codes.
     */
    static class ColorMapper {
        /**
         * Maps the given color to valid QR-lib colors.
         * If no color is given, fallback is returned.
         *
         * @param color    can either be a String or encoded hex-RGB value.
         * @param fallback existing color if no matching took place or given value cannot be parsed.
         * @return color mapped to QR-lib defaults or RGB or fallback passed in as parameter.
         */
        public static Color getColor(Optional<String> color, Color fallback) {
            if (color.isPresent()) {
                switch (color.get().toLowerCase()) {
                    case "blue":
                        return Color.BLUE;
                    case "green":
                        return Color.GREEN;
                    case "red":
                        return Color.RED;
                    case "white":
                        return Color.WHITE;
                    case "black":
                        return Color.BLACK;
                    default:
                        // https://rgbcolorcode.com/color/99AABB
                        // https://rgbcolorcode.com/color/converter/
                        try {
                            return new Color(color.get());
                        } catch (IllegalArgumentException e) {
                            // fallthrough intentionally to return fallback
                            log.info("Color '{}' is invalid, will return fallback due to: {}", color.get(), e.getMessage());
                        }
                }
            }

            return fallback;
        }

    }

}
